#![cfg_attr(not(feature = "std"), no_std)]

pub mod cpu_entropy;
pub mod entropy;

pub use entropy::{fill_random_bytes, HardwareEntropyPool};

#[cfg(test)]
mod tests {
    #[cfg(feature = "std")]
    use rand_core::{Rng, TryRng};
    use crate::entropy::fill_random_bytes;
    #[cfg(feature = "std")]
    use super::*;

    #[test]
    fn test_generate_random_bytes() {
        let mut bytes = [0u8; 64];
        fill_random_bytes(&mut bytes);
        assert_eq!(bytes.len(), 64);
        assert!(bytes.iter().any(|&b| b != 0), "Generated bytes should not be all zeros");
    }

    #[test]
    #[cfg(feature = "std")]
    fn test_hardware_entropy_pool() {
        let mut entropy_pool = HardwareEntropyPool::new();
        let mut bytes = vec![0u8; 64];
        entropy_pool.fill_bytes(&mut bytes);
        assert_eq!(bytes.iter().any(|&b| b != 0), true);
    }

    #[test]
    #[cfg(feature = "std")]
    fn test_pool_reseed() {
        let mut entropy_pool = HardwareEntropyPool::new();
        entropy_pool.reseed().unwrap();
        let mut bytes = vec![0u8; 64];
        entropy_pool.fill_bytes(&mut bytes);
        assert_eq!(bytes.iter().any(|&b| b != 0), true);
    }

    #[test]
    #[cfg(feature = "std")]
    fn test_reseed_resets_counter() {
        let mut pool = HardwareEntropyPool::new();
        let mut buf = vec![0u8; 500];

        pool.fill_bytes(&mut buf);
        assert_eq!(pool.counter(), 500);
        pool.reseed().unwrap();

        assert_eq!(pool.counter(), 0);
    }

    #[test]
    #[cfg(feature = "std")]
    fn test_reseed_changes_crypto_state() {
        let mut pool1 = HardwareEntropyPool::new();
        let mut pool2 = pool1.clone();

        let mut dummy = vec![0u8; 500];
        pool1.fill_bytes(&mut dummy);
        pool2.fill_bytes(&mut dummy);

        pool1.reseed().unwrap();

        let mut bytes1 = [0u8; 500];
        let mut bytes2 = [0u8; 500];
        pool1.fill_bytes(&mut bytes1);
        pool2.fill_bytes(&mut bytes2);

        assert_ne!(bytes1, bytes2);
    }

    #[test]
    #[ignore]
    // use "cargo test -- --nocapture --ignored" for benchmark
    fn bench_speed() {
        use std::time::Instant;
        let mut buf = vec![0u8; 10_000_000]; // 10 mb
        let start = Instant::now();
        let mut pool = crate::entropy::HardwareEntropyPool::new();
        let duration_init = start.elapsed();
        let start_gen = Instant::now();
        let _ = pool.try_fill_bytes(&mut buf);
        let duration_gen = start_gen.elapsed();
        let speed_mb_s = 10.0 / duration_gen.as_secs_f64();
        let start_reseed = Instant::now();
        pool.reseed().unwrap();
        let elapsed_reseed = start_reseed.elapsed();
        println!("\n=== SPEED BENCHMARK ===");
        println!("Pool Initialization time: {:?}", duration_init);
        println!("Generated 10 MB in: {:?}", duration_gen);
        println!("Throughput: {:.2} MB/s", speed_mb_s);
        println!("Elapsed reseed: {:?}", elapsed_reseed);
        println!("========================\n");
    }
}